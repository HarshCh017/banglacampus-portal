VERIFIED_COLLEGES.forEach((college) => {
  const photoData = COLLEGE_PHOTOS[college.slug];
  if (photoData) {
    college.campusImageUrl = photoData.primaryImage;
    college.campusImageCaption = photoData.caption;
    // Strict non-duplicate deduplication: ensure no gallery image repeats the primary banner image
    // or repeats another image within the gallery
    const seenUrls = new Set<string>([photoData.primaryImage]);
    const uniqueGallery = (photoData.gallery || []).filter((item) => {
      if (seenUrls.has(item.url)) {
        return false;
      }
      seenUrls.add(item.url);
      return true;
    });
    college.campusImagesGallery = uniqueGallery;
    college.imageAttribution = photoData.attribution;
  }
});

